// Multiboot1 header + 32-bit to 64-bit long mode transition.
//
// Flow: BIOS/QEMU loads us in 32-bit protected mode via Multiboot1.
// We set up identity-mapped page tables, enable long mode, load a
// 64-bit GDT, far-jump to 64-bit code, then call the Quadrate _start.

// ---- Multiboot1 header ----
.set MAGIC,    0x1BADB002
.set FLAGS,    0x00000003
.set CHECKSUM, -(MAGIC + FLAGS)

.section .multiboot, "a"
.align 4
.long MAGIC
.long FLAGS
.long CHECKSUM

// ---- 32-bit bootstrap GDT (temporary, just for the long-mode jump) ----
.section .data
.align 16
boot_gdt:
	.quad 0                          // 0x00: null
	.quad 0x00AF9A000000FFFF         // 0x08: 64-bit code (L=1, D=0)
	.quad 0x00AF92000000FFFF         // 0x10: 64-bit data
boot_gdt_end:

boot_gdt_ptr:
	.word boot_gdt_end - boot_gdt - 1
	.quad boot_gdt

// ---- Page tables: identity-map first 2MB (using 2MB huge pages) ----
.section .bss
.align 4096
pml4:
	.skip 4096
pdpt:
	.skip 4096
pdt:
	.skip 4096

// ---- 64-bit stack ----
.align 16
stack_bottom:
	.skip 16384
stack_top:

// ---- 32-bit entry point ----
.section .text
.code32
.global _kernel_entry
.type _kernel_entry, @function
_kernel_entry:
	// Disable interrupts
	cli

	// Set up temporary 32-bit stack
	movl $stack_top, %esp

	// ---- Set up identity-mapped page tables ----
	// PML4[0] -> PDPT
	movl $pdpt, %eax
	orl $0x3, %eax               // present + writable
	movl %eax, (pml4)
	movl $0, (pml4 + 4)

	// PDPT[0] -> PDT
	movl $pdt, %eax
	orl $0x3, %eax
	movl %eax, (pdpt)
	movl $0, (pdpt + 4)

	// PDT[0] -> 2MB huge page at physical 0x000000
	movl $0x83, (pdt)            // present + writable + huge (bit 7)
	movl $0, (pdt + 4)

	// PDT[1] -> 2MB huge page at physical 0x200000
	movl $0x200083, (pdt + 8)
	movl $0, (pdt + 12)

	// ---- Enable PAE (CR4.PAE = bit 5) ----
	movl %cr4, %eax
	orl $0x20, %eax
	movl %eax, %cr4

	// ---- Load PML4 into CR3 ----
	movl $pml4, %eax
	movl %eax, %cr3

	// ---- Enable long mode (IA32_EFER.LME = bit 8) ----
	movl $0xC0000080, %ecx
	rdmsr
	orl $0x100, %eax
	wrmsr

	// ---- Enable paging (CR0.PG = bit 31) ----
	movl %cr0, %eax
	orl $0x80000000, %eax
	movl %eax, %cr0

	// ---- Load 64-bit GDT ----
	lgdt (boot_gdt_ptr)

	// ---- Far jump to 64-bit code segment ----
	ljmp $0x08, $_start64

// ---- 64-bit entry point ----
.code64
.global _start64
_start64:
	// Set up 64-bit segment registers
	movw $0x10, %ax
	movw %ax, %ds
	movw %ax, %es
	movw %ax, %fs
	movw %ax, %gs
	movw %ax, %ss

	// Set up 64-bit stack
	movq $stack_top, %rsp

	// Call Quadrate _start (generated by quadc --freestanding)
	call _start

	// If _start returns, halt
1:	cli
	hlt
	jmp 1b
.size _kernel_entry, . - _kernel_entry
